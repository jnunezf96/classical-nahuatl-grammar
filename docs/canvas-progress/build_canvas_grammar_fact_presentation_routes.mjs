import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const inputs = [
  "docs/canvas-progress/checkpoint009_fact_selection.json",
  "docs/canvas-progress/checkpoint010_fact_selection.json",
];
const outputPath = path.join(root, "src/core/classical/canvas_grammar_fact_presentation_routes.mjs");
const selections = await Promise.all(inputs.map(async (relativePath) =>
  JSON.parse(await readFile(path.join(root, relativePath), "utf8"))));
const ownerRoutes = new Map();
for (const selection of selections) {
  for (const owner of selection.owners) {
    const existing = ownerRoutes.get(owner.ownerId);
    if (existing && JSON.stringify(existing) !== JSON.stringify(owner)) {
      throw new Error(`presentation-owner-route-drift:${owner.ownerId}`);
    }
    ownerRoutes.set(owner.ownerId, owner);
  }
}
const routes = selections.flatMap((selection) => selection.atoms.map((atom) => {
  const owner = ownerRoutes.get(atom.semanticOwnerId);
  if (!owner) throw new Error(`presentation-owner-route-missing:${atom.atomId}`);
  return {
    atomId: atom.atomId,
    semanticOwnerId: atom.semanticOwnerId,
    prefix: owner.prefix,
    selection: owner.selection,
    requestedFacet: owner.requestedFacet,
  };
})).sort((left, right) => left.atomId.localeCompare(right.atomId));
if (routes.length !== 1000 || new Set(routes.map((route) => route.atomId)).size !== 1000) {
  throw new Error(`presentation-route-count:${routes.length}`);
}

const moduleText = `// Generated by docs/canvas-progress/build_canvas_grammar_fact_presentation_routes.mjs.\n`
  + `// Routes select typed owner APIs for presentation only; they never authorize grammar.\n\n`
  + `const ROUTES = Object.freeze(${JSON.stringify(routes, null, 2)}.map(Object.freeze));\n`
  + `const BY_ATOM_ID = new Map(ROUTES.map((route) => [route.atomId, route]));\n\n`
  + `export function getClassicalCanvasGrammarFactPresentationRoute(atomId = "") {\n`
  + `  return BY_ATOM_ID.get(String(atomId)) || null;\n`
  + `}\n\n`
  + `export function listClassicalCanvasGrammarFactPresentationRoutes() { return ROUTES; }\n`;
await writeFile(outputPath, moduleText, "utf8");
console.log(JSON.stringify({ routes: routes.length, owners: ownerRoutes.size }));
