import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const ledgerPath = path.join(root, "docs/ANDREWS_ATOM_LEDGER.json");
const registryPath = path.join(root, "src/core/classical/canvas_grammar_fact_registry.mjs");
const selectionPath = path.join(root, "docs/canvas-progress/checkpoint009_fact_selection.json");
const checkpointSize = 500;

function fingerprint(record) {
  let hash = 0x811c9dc5;
  const text = [
    record.atomId,
    record.semanticOwnerId,
    record.canvasSection,
    record.canvasSpan,
    record.statement,
    record.projectRole,
  ].join("\u241f").normalize("NFC");
  for (const symbol of text) {
    hash ^= symbol.codePointAt(0);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return `fnv1a32:${hash.toString(16).padStart(8, "0")}`;
}

const ledgerText = await readFile(ledgerPath, "utf8");
const ledger = JSON.parse(ledgerText);
const fields = Object.fromEntries(ledger.codebook.atomTuple.map((field, index) => [field, index]));
const records = ledger.atoms
  .filter((atom) => atom[fields.force] === "grammar-bearing"
    && atom[fields.projectRole] === "read-only-grammar-fact")
  .map((atom) => {
    const record = {
      atomId: atom[fields.atomId],
      semanticOwnerId: atom[fields.semanticOwnerId],
      canvasSection: atom[fields.canvasSection],
      canvasSpan: atom[fields.canvasSpan],
      statement: atom[fields.meaning],
      projectRole: atom[fields.projectRole],
    };
    return { ...record, contentFingerprint: fingerprint(record) };
  })
  .sort((left, right) => left.atomId.localeCompare(right.atomId));

let preservedSelection = null;
try {
  preservedSelection = JSON.parse(await readFile(selectionPath, "utf8"));
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

let selectedAtomIds = [];
let owners = [];
let sourceLedgerDigest = `sha256:${createHash("sha256").update(ledgerText).digest("hex")}`;
if (preservedSelection?.checkpoint === "009") {
  selectedAtomIds = preservedSelection.atoms.map((record) => record.atomId);
  owners = preservedSelection.owners;
  sourceLedgerDigest = preservedSelection.sourceLedgerDigest;
} else {
  const pendingByOwner = new Map();
  for (const atom of ledger.atoms) {
    if (atom[fields.checkedStatus] !== "exact-observation-pending"
      || atom[fields.projectRole] !== "read-only-grammar-fact") continue;
    const ownerId = atom[fields.semanticOwnerId];
    if (!pendingByOwner.has(ownerId)) pendingByOwner.set(ownerId, []);
    pendingByOwner.get(ownerId).push(atom[fields.atomId]);
  }
  const rankedOwners = [...pendingByOwner.entries()]
    .sort((left, right) => right[1].length - left[1].length
      || left[0].localeCompare(right[0]));
  const selectedOwnerIds = [];
  for (const [ownerId, atomIds] of rankedOwners) {
    if (selectedAtomIds.length >= checkpointSize) break;
    selectedOwnerIds.push(ownerId);
    selectedAtomIds.push(...atomIds.sort().slice(0, checkpointSize - selectedAtomIds.length));
  }
  for (const ownerId of selectedOwnerIds) {
    const specPath = path.join(root, `src/core/classical/nuclear-owner-specs/${ownerId}.mjs`);
    const specText = await readFile(specPath, "utf8");
    const prefix = specText.match(/"prefix": "([^"]+)"/)?.[1] || "";
    const coordinate = specText.match(/"(claim-[^"]+::[^"]+)": \{/)?.[1] || "";
    if (!prefix || !coordinate) throw new Error(`owner-spec-coordinate-missing:${ownerId}`);
    const [selection, requestedFacet] = coordinate.split("::");
    owners.push({ ownerId, prefix, selection, requestedFacet });
  }
}

const selectedAtomIdSet = new Set(selectedAtomIds);
const selectedRecords = records.filter((record) => selectedAtomIdSet.has(record.atomId));
const selectedAtoms = selectedRecords.map((record) => ({
  atomId: record.atomId,
  semanticOwnerId: record.semanticOwnerId,
}));

const moduleText = `// Generated by docs/canvas-progress/build_canvas_grammar_fact_registry.mjs.\n`
  + `// These are non-authorizing Canvas grammar explanations. Generation remains with typed owners.\n\n`
  + `const freeze = Object.freeze;\n`
  + `const records = ${JSON.stringify(records, null, 2)};\n\n`
  + `function deepFreeze(value) {\n`
  + `  if (!value || typeof value !== "object" || Object.isFrozen(value)) return value;\n`
  + `  for (const child of Object.values(value)) deepFreeze(child);\n`
  + `  return freeze(value);\n`
  + `}\n\n`
  + `export function fingerprintClassicalCanvasGrammarFact(record = {}) {\n`
  + `  let hash = 0x811c9dc5;\n`
  + `  const text = [record.atomId, record.semanticOwnerId, record.canvasSection, record.canvasSpan, record.statement, record.projectRole].join("\\u241f").normalize("NFC");\n`
  + `  for (const symbol of text) { hash ^= symbol.codePointAt(0); hash = Math.imul(hash, 0x01000193) >>> 0; }\n`
  + `  return \`fnv1a32:\${hash.toString(16).padStart(8, "0")}\`;\n`
  + `}\n\n`
  + `const RECORDS = deepFreeze(records);\n`
  + `const BY_ATOM_ID = new Map(RECORDS.map((record) => [record.atomId, record]));\n\n`
  + `export function isClassicalCanvasGrammarFactRecord(record = null) {\n`
  + `  return Boolean(record && record.projectRole === "read-only-grammar-fact" && record.contentFingerprint === fingerprintClassicalCanvasGrammarFact(record));\n`
  + `}\n\n`
  + `export function getClassicalCanvasGrammarFactRecord(atomId = "") {\n`
  + `  return BY_ATOM_ID.get(String(atomId)) || null;\n`
  + `}\n\n`
  + `export function listClassicalCanvasGrammarFactRecords() { return RECORDS; }\n`;

const selection = {
  schemaVersion: 1,
  kind: "classical-canvas-grammar-fact-checkpoint-selection",
  checkpoint: "009",
  selectionRule: "largest pending read-only grammar-fact owners, owner-id tie break, atom-id order",
  counts: {
    registryFacts: records.length,
    selectedOwners: owners.length,
    selectedAtoms: selectedAtoms.length,
  },
  sourceLedgerDigest,
  owners,
  atoms: selectedAtoms,
};

if (selection.counts.selectedAtoms !== checkpointSize) {
  throw new Error(`checkpoint-selection-count:${selection.counts.selectedAtoms}`);
}
await writeFile(registryPath, moduleText, "utf8");
await writeFile(selectionPath, `${JSON.stringify(selection, null, 2)}\n`, "utf8");
console.log(JSON.stringify(selection.counts));
