export function assertRuntimeInstallerCoverage(runtimeInstallers = RUNTIME_INSTALLERS) {
    if (!(runtimeInstallers instanceof Map)) {
        throw new TypeError("The modern runtime installer manifest must be a Map.");
    }
    const missingInstallers = [];
    const invalidPaths = [];
    for (const [modulePath, installer] of runtimeInstallers.entries()) {
        if (!String(modulePath || "").endsWith(".mjs")) {
            invalidPaths.push(String(modulePath || ""));
        }
        if (typeof installer !== "function") {
            missingInstallers.push(String(modulePath || ""));
        }
    }
    if (invalidPaths.length || missingInstallers.length) {
        const details = [
            invalidPaths.length ? `invalid module paths: ${invalidPaths.join(", ")}` : "",
            missingInstallers.length ? `missing installers: ${missingInstallers.join(", ")}` : "",
        ].filter(Boolean).join("; ");
        throw new Error(`Modern runtime installer coverage failed (${details}).`);
    }
    return Object.freeze({
        moduleCount: runtimeInstallers.size,
        modulePaths: Object.freeze([...runtimeInstallers.keys()]),
    });
}

function cloneDescriptorMap(object, keys) {
    const descriptors = {};
    keys.forEach((key) => {
        const descriptor = Object.getOwnPropertyDescriptor(object, key);
        if (descriptor) {
            descriptors[key] = descriptor;
        }
    });
    return descriptors;
}

function defineDescriptors(targetObject, descriptors) {
    if (!targetObject || typeof targetObject !== "object") {
        return;
    }
    Object.defineProperties(targetObject, descriptors);
}

function cloneFallbackDescriptor(descriptor) {
    if (!descriptor) {
        return undefined;
    }
    return {
        ...descriptor,
        configurable: true,
    };
}

function createInstallerModuleTarget(runtimeObject) {
    const moduleTarget = Object.create(null);
    const moduleWindowTarget = Object.create(null);
    const publishedCapabilityNames = new Set();
    let moduleProxy = null;
    const readFallback = (propertyName) => Reflect.get(
        runtimeObject,
        propertyName,
        runtimeObject,
    );
    const readWindowFallback = (propertyName) => {
        if (Object.prototype.hasOwnProperty.call(runtimeObject, propertyName)) {
            return readFallback(propertyName);
        }
        const windowObject = runtimeObject.window;
        const value = Reflect.get(windowObject, propertyName, windowObject);
        return typeof value === "function"
            ? value.bind(windowObject)
            : value;
    };
    const moduleWindowProxy = new Proxy(moduleWindowTarget, {
        get(target, propertyName, receiver) {
            if (Reflect.has(target, propertyName)) {
                return Reflect.get(target, propertyName, receiver);
            }
            return readWindowFallback(propertyName);
        },
        set(target, propertyName, value, receiver) {
            if (
                Object.prototype.hasOwnProperty.call(
                    runtimeObject,
                    propertyName,
                )
            ) {
                return Reflect.set(
                    runtimeObject,
                    propertyName,
                    value,
                    runtimeObject,
                );
            }
            return Reflect.set(target, propertyName, value, receiver);
        },
        defineProperty(target, propertyName, descriptor) {
            return Reflect.defineProperty(target, propertyName, descriptor);
        },
        getOwnPropertyDescriptor(target, propertyName) {
            return Reflect.getOwnPropertyDescriptor(target, propertyName)
                || cloneFallbackDescriptor(
                    Reflect.getOwnPropertyDescriptor(
                        runtimeObject.window,
                        propertyName,
                    ),
                )
                || cloneFallbackDescriptor(
                    Reflect.getOwnPropertyDescriptor(
                        runtimeObject,
                        propertyName,
                    ),
                );
        },
        has(target, propertyName) {
            return Reflect.has(target, propertyName)
                || Reflect.has(runtimeObject, propertyName)
                || Reflect.has(runtimeObject.window, propertyName);
        },
        ownKeys(target) {
            return [
                ...new Set([
                    ...Reflect.ownKeys(runtimeObject.window),
                    ...Reflect.ownKeys(runtimeObject),
                    ...Reflect.ownKeys(target),
                ]),
            ];
        },
    });
    moduleProxy = new Proxy(moduleTarget, {
        get(target, propertyName, receiver) {
            if (propertyName === "globalThis") {
                return moduleProxy;
            }
            if (propertyName === "window") {
                return moduleWindowProxy;
            }
            if (Reflect.has(target, propertyName)) {
                return Reflect.get(target, propertyName, receiver);
            }
            return readFallback(propertyName);
        },
        set(target, propertyName, value, receiver) {
            if (Reflect.has(target, propertyName)) {
                const descriptor =
                    Reflect.getOwnPropertyDescriptor(target, propertyName);
                const updated = Reflect.set(
                    target,
                    propertyName,
                    value,
                    receiver,
                );
                if (
                    updated
                    && publishedCapabilityNames.has(String(propertyName))
                    && descriptor
                    && Object.prototype.hasOwnProperty.call(
                        descriptor,
                        "value",
                    )
                ) {
                    Reflect.set(
                        runtimeObject,
                        propertyName,
                        value,
                        runtimeObject,
                    );
                }
                return updated;
            }
            if (
                Object.prototype.hasOwnProperty.call(
                    runtimeObject,
                    propertyName,
                )
            ) {
                return Reflect.set(
                    runtimeObject,
                    propertyName,
                    value,
                    runtimeObject,
                );
            }
            return Reflect.set(target, propertyName, value, receiver);
        },
        defineProperty(target, propertyName, descriptor) {
            const defined = Reflect.defineProperty(
                target,
                propertyName,
                descriptor,
            );
            if (
                defined
                && publishedCapabilityNames.has(String(propertyName))
            ) {
                Reflect.defineProperty(
                    runtimeObject,
                    propertyName,
                    descriptor,
                );
            }
            return defined;
        },
        getOwnPropertyDescriptor(target, propertyName) {
            return Reflect.getOwnPropertyDescriptor(target, propertyName)
                || cloneFallbackDescriptor(
                    Reflect.getOwnPropertyDescriptor(
                        runtimeObject,
                        propertyName,
                    ),
                );
        },
        has(target, propertyName) {
            return Reflect.has(target, propertyName)
                || Reflect.has(runtimeObject, propertyName);
        },
        ownKeys(target) {
            return [
                ...new Set([
                    ...Reflect.ownKeys(runtimeObject),
                    ...Reflect.ownKeys(target),
                ]),
            ];
        },
    });
    return Object.freeze({
        moduleProxy,
        moduleTarget,
        moduleWindowTarget,
        publishCapability(propertyName, descriptor) {
            Reflect.defineProperty(
                runtimeObject,
                propertyName,
                descriptor,
            );
            publishedCapabilityNames.add(String(propertyName));
        },
    });
}

function bindRuntimeFunction(primaryObject, secondaryObject, propertyName, fallback = undefined) {
    const owner = typeof primaryObject?.[propertyName] === "function"
        ? primaryObject
        : (typeof secondaryObject?.[propertyName] === "function" ? secondaryObject : null);
    return owner ? owner[propertyName].bind(owner) : fallback;
}

function buildRuntimeBase({
    globalObject = globalThis,
    windowObject = globalObject?.window || globalObject,
    documentObject = globalObject?.document || windowObject?.document || null,
    runtimeConfig = null,
    extraGlobals = {},
} = {}) {
    const runtimeObject = {
        console: globalObject?.console || console,
        window: windowObject,
        document: documentObject,
        localStorage: globalObject?.localStorage || windowObject?.localStorage,
        navigator: globalObject?.navigator || windowObject?.navigator,
        fetch: bindRuntimeFunction(globalObject, windowObject, "fetch"),
        URL: globalObject?.URL,
        URLSearchParams: globalObject?.URLSearchParams || windowObject?.URLSearchParams,
        Blob: globalObject?.Blob,
        Event: globalObject?.Event,
        CustomEvent: globalObject?.CustomEvent,
        DOMParser: globalObject?.DOMParser,
        setTimeout: bindRuntimeFunction(globalObject, windowObject, "setTimeout", setTimeout),
        clearTimeout: bindRuntimeFunction(globalObject, windowObject, "clearTimeout", clearTimeout),
        setInterval: bindRuntimeFunction(globalObject, windowObject, "setInterval", setInterval),
        clearInterval: bindRuntimeFunction(globalObject, windowObject, "clearInterval", clearInterval),
        requestAnimationFrame: bindRuntimeFunction(globalObject, windowObject, "requestAnimationFrame"),
        cancelAnimationFrame: bindRuntimeFunction(globalObject, windowObject, "cancelAnimationFrame"),
        performance: globalObject?.performance,
        getComputedStyle: bindRuntimeFunction(globalObject, windowObject, "getComputedStyle"),
        ...extraGlobals,
    };
    runtimeObject.globalThis = runtimeObject;
    if (runtimeConfig) {
        runtimeObject.__CLASSICAL_RUNTIME_CONFIG__ = runtimeConfig;
        runtimeObject.__CLASSICAL_RUNTIME_PATHS__ = runtimeConfig.paths;
    }
    return runtimeObject;
}

export async function createRuntimeInstance({
    collectModuleInspectionDescriptors = false,
    ...options
} = {}) {
    assertRuntimeInstallerCoverage();
    const runtimeObject = buildRuntimeBase(options);
    const initialKeys = new Set(Reflect.ownKeys(runtimeObject));
    const loadedModules = [];
    const capabilityOwnerByKey = new Map();
    const moduleCapabilityDescriptorsByPath = new Map();
    const moduleInspectionDescriptors = {};
    let issueGrammarFrameOwnerCapability = null;
    for (const [modulePath, installer] of RUNTIME_INSTALLERS.entries()) {
        const installerTarget = createInstallerModuleTarget(runtimeObject);
        const privateDependencyDescriptors = {};
        for (const [providerPath, capabilityNames] of Object.entries(
            PRIVATE_INSTALLER_DEPENDENCIES[modulePath] || {},
        )) {
            const providerDescriptors =
                moduleCapabilityDescriptorsByPath.get(providerPath);
            if (!providerDescriptors) {
                throw new Error(
                    `Private runtime dependency provider must install first: ${providerPath} -> ${modulePath}`,
                );
            }
            for (const capabilityName of capabilityNames) {
                const descriptor = providerDescriptors[capabilityName];
                if (!descriptor) {
                    throw new Error(
                        `Private runtime dependency capability missing: ${providerPath}:${capabilityName}`,
                    );
                }
                privateDependencyDescriptors[capabilityName] = descriptor;
            }
        }
        const moduleDependencyCapabilities = {};
        Object.defineProperties(
            moduleDependencyCapabilities,
            privateDependencyDescriptors,
        );
        Object.freeze(moduleDependencyCapabilities);
        const installerContext = {
            modulePath,
            moduleDependencyCapabilities,
            ...(modulePath === "src/core/grammar/frame.mjs" ? {
                registerGrammarFrameOwnerCapabilityIssuer(issuer) {
                    if (issueGrammarFrameOwnerCapability !== null || typeof issuer !== "function") {
                        throw new Error("The grammar-frame owner-capability issuer may be registered exactly once.");
                    }
                    issueGrammarFrameOwnerCapability = issuer;
                },
            } : {}),
            ...(typeof issueGrammarFrameOwnerCapability === "function" ? {
                grammarFrameOwnerCapability: issueGrammarFrameOwnerCapability(modulePath),
            } : {}),
        };
        await installer(
            installerTarget.moduleProxy,
            Object.freeze(installerContext),
        );
        const declaredDescriptors = Object.getOwnPropertyDescriptors(
            installerTarget.moduleTarget,
        );
        moduleCapabilityDescriptorsByPath.set(modulePath, declaredDescriptors);
        const declaredCapabilities = Reflect.ownKeys(declaredDescriptors)
            .map(key => String(key))
            .sort();
        if (collectModuleInspectionDescriptors) {
            declaredCapabilities.forEach(capabilityName => {
                if (
                    !Object.prototype.hasOwnProperty.call(
                        moduleInspectionDescriptors,
                        capabilityName,
                    )
                ) {
                    moduleInspectionDescriptors[capabilityName] =
                        declaredDescriptors[capabilityName];
                }
            });
        }
        const publishableCapabilities = declaredCapabilities
            .filter(isRuntimeCrossModuleCapability);
        const overwrittenCapabilities = publishableCapabilities
            .filter(
                capabilityName => capabilityOwnerByKey.has(capabilityName),
            )
            .map(capabilityName => Object.freeze({
                capabilityName,
                previousOwner: capabilityOwnerByKey.get(capabilityName),
            }));
        const overwrittenCapabilityNames = new Set(
            overwrittenCapabilities.map(
                record => record.capabilityName,
            ),
        );
        const installedCapabilities = publishableCapabilities
            .filter(
                capabilityName =>
                    !overwrittenCapabilityNames.has(capabilityName),
            );
        installedCapabilities.forEach(capabilityName => {
            installerTarget.publishCapability(
                capabilityName,
                declaredDescriptors[capabilityName],
            );
            capabilityOwnerByKey.set(capabilityName, modulePath);
        });
        const privateCapabilities = declaredCapabilities.filter(
            capabilityName =>
                !installedCapabilities.includes(capabilityName)
                && !overwrittenCapabilityNames.has(capabilityName),
        );
        loadedModules.push(Object.freeze({
            esmModulePath: modulePath,
            declaredCapabilities: Object.freeze(declaredCapabilities),
            installedCapabilities: Object.freeze(installedCapabilities),
            privateCapabilities: Object.freeze(privateCapabilities),
            overwrittenCapabilities: Object.freeze(overwrittenCapabilities),
        }));
    }
    const exposedKeys = Reflect.ownKeys(runtimeObject).filter((key) => !initialKeys.has(key));
    const exposedDescriptors = cloneDescriptorMap(runtimeObject, exposedKeys);
    runtimeObject.__CLASSICAL_ESM_PRELOADS__ = loadedModules;
    return {
        runtimeObject,
        exposedDescriptors,
        loadedModules,
        moduleInspectionDescriptors: collectModuleInspectionDescriptors
            ? moduleInspectionDescriptors
            : null,
    };
}

export function attachRuntimeBindings(targetObject, runtimeInstance) {
    if (!targetObject || typeof targetObject !== "object" || !runtimeInstance) {
        return targetObject;
    }
    defineDescriptors(targetObject, runtimeInstance.exposedDescriptors || {});
    if (runtimeInstance.runtimeObject?.__CLASSICAL_RUNTIME_CONFIG__) {
        targetObject.__CLASSICAL_RUNTIME_CONFIG__ = runtimeInstance.runtimeObject.__CLASSICAL_RUNTIME_CONFIG__;
        targetObject.__CLASSICAL_RUNTIME_PATHS__ = runtimeInstance.runtimeObject.__CLASSICAL_RUNTIME_PATHS__;
    }
    targetObject.__CLASSICAL_ESM_PRELOADS__ = runtimeInstance.loadedModules || [];
    return targetObject;
}
